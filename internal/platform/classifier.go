// Classify returns the platform name for a domain, or "" if unknown.
func (c *Classifier) Classify(domain string) string {
	domain = strings.ToLower(strings.TrimSpace(domain))
	if domain == "" {
		return ""
	}

	// 1. Exact match
	if v, ok := c.exact[domain]; ok {
		return v
	}

	// 2. Suffix match (longest suffix first)
	for i := 0; i < len(domain); i++ {
		if domain[i] == '.' {
			suffix := domain[i:]
			if v, ok := c.suffix[suffix]; ok {
				return v
			}
		}
	}

	// 3. Keyword match (substring)
	for _, rule := range c.keywords {
		if strings.Contains(domain, rule.keyword) {
			return rule.platform
		}
	}

	return ""
}